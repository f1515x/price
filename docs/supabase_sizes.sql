-- 在 Supabase SQL Editor 中执行；支持首次建表和重复升级。
create table if not exists public.orders (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    contract text,
    activation_price numeric,
    side text,
    amount bigint,
    value numeric,
    timestamp bigint,
    quanto_multiplier numeric,
    order_price_round numeric
);

-- 保留现有 id、created_at 和所有历史记录。
alter table public.orders
    add column if not exists contract text,
    add column if not exists activation_price numeric,
    add column if not exists side text,
    add column if not exists amount bigint,
    add column if not exists value numeric,
    add column if not exists timestamp bigint,
    add column if not exists quanto_multiplier numeric,
    add column if not exists order_price_round numeric;

comment on column public.orders.timestamp is 'Sizes 报告的 Unix 毫秒时间戳';

comment on column public.orders.quanto_multiplier is 'Gate 合约乘数，保留完整数值精度';
comment on column public.orders.order_price_round is 'Gate 下单价格步长，保留完整数值精度';
